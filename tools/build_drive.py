def single_html(page="sp-202_loader.html"):
    html = open(os.path.join(APP, page), encoding="utf8").read()

    def css(m):
        return "<style>\n" + open(os.path.join(APP, m.group(1)), encoding="utf8").read() + "</style>"

    def js(m):
        code = open(os.path.join(APP, m.group(1)), encoding="utf8").read()
        return "<script>\n" + code.replace("</script", "<\\/script") + "</script>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html = re.sub(r'<script src="([^"]+)"></script>', js, html)
    return html.replace("%VERSION%", VERSION).encode("utf8")


def c_array(f, name, data):
    f.write(f"const uint32_t {name}_len = {len(data)};\n")
    f.write(f"const uint8_t {name}[] = {{\n")
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_c")
    ap.add_argument("--html", help="also write the single-file page here")
    ap.add_argument("--generic", action="store_true", help="the generic card: Generic Card Manager (app/generic_loader.html)")
    a = ap.parse_args()
    page = single_html("generic_loader.html" if a.generic else "sp-202_loader.html")
    readme = (README_GENERIC if a.generic else README).replace("%PAGE%", GENERIC_PAGE if a.generic else SP202_PAGE)
    readme = readme.replace("\n", "\r\n").encode("ascii")
    now = datetime.datetime.now()
    with open(a.out_c, "w") as f:
        f.write("// Generated by tools/build_drive.py from app/: do not edit.\n#include <stdint.h>\n\n")
        f.write(f"const uint16_t usb_drive_build_date = {((now.year - 1980) << 9) | (now.month << 5) | now.day};\n")
        f.write(f"const uint16_t usb_drive_build_time = {(now.hour << 11) | (now.minute << 5) | (now.second // 2)};\n\n")
        c_array(f, "usb_drive_page", page)
        c_array(f, "usb_drive_readme", readme)
    if a.html:
        open(a.html, "wb").write(page)
    print(f"USB drive: page {len(page)} bytes, README {len(readme)} bytes")
